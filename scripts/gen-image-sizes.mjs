#!/usr/bin/env node
/**
 * Gera src/lib/_generated-image-sizes.ts: largura e altura reais de cada foto
 * que pode aparecer no corpo de um artigo.
 *
 * Por que isso existe: no MDX (e no markdown vindo do Supabase) a sintaxe de
 * imagem e `![alt](/caminho)` — nao ha onde declarar dimensao. O componente
 * `img` do MDX caia num padrao de 800x450, mas as fotos do canil sao quase
 * todas retrato (medido: 0,47 a 1,50 de proporcao, a maioria em 0,56). Servir
 * 16:9 para uma foto 9:16 desloca o texto quando a imagem carrega — e CLS puro,
 * exatamente a metrica que o artigo com foto deveria melhorar, nao piorar.
 *
 * Com a dimensao real em maos, o next/image reserva o espaco certo antes do
 * download e nada pula.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

// So as pastas de onde uma foto de corpo de artigo pode sair. Varrer `public`
// inteiro traria favicon, logo e selo — 200 entradas que nenhum artigo usa.
const PASTAS = ['filhotes', 'images'];
// Fora das pastas, a raiz de public/ entra sem descer em subpasta: 13 dos 30
// artigos usam /spitz-hero-desktop.webp como capa, que fica solto ali. Sem
// medida a capa caia num 16:9 fixo sendo 3:2, e o artigo pulava ao carregar.
// Sao 14 arquivos — o custo que o comentario acima temia nao existe na raiz.
const RAIZ_TAMBEM = true;
const EXT = /\.(jpe?g|png|webp|avif)$/i;

async function varrer(dirAbs, prefixoUrl, saida, { recursivo = true } = {}) {
  let entradas;
  try {
    entradas = await fs.readdir(dirAbs, { withFileTypes: true });
  } catch {
    return; // pasta ausente nao derruba o build
  }
  for (const e of entradas.sort((a, b) => a.name.localeCompare(b.name, 'pt-BR'))) {
    if (e.name.startsWith('.')) continue; // lixeira do Android (.trashed-*) e afins
    const abs = path.join(dirAbs, e.name);
    const url = `${prefixoUrl}/${e.name}`;
    if (e.isDirectory()) {
      if (recursivo) await varrer(abs, url, saida);
      continue;
    }
    if (!EXT.test(e.name)) continue;
    try {
      const { width, height } = await sharp(abs).metadata();
      if (width && height) saida[url] = [width, height];
    } catch {
      // arquivo corrompido ou formato que o sharp nao le: fica de fora e o
      // componente cai no padrao, em vez de quebrar o build inteiro.
    }
  }
}

async function main() {
  const tamanhos = {};
  for (const pasta of PASTAS) {
    await varrer(path.resolve('public', pasta), `/${pasta}`, tamanhos);
  }
  if (RAIZ_TAMBEM) {
    await varrer(path.resolve('public'), '', tamanhos, { recursivo: false });
  }

  const chaves = Object.keys(tamanhos).sort();
  const linhas = chaves.map((k) => `  ${JSON.stringify(k)}: [${tamanhos[k][0]}, ${tamanhos[k][1]}],`);

  const conteudo =
    `// AUTO-GENERATED by scripts/gen-image-sizes.mjs — nao editar a mao.\n` +
    `// Dimensao real (largura, altura) das fotos servidas de /public.\n\n` +
    `const IMAGE_SIZES: Record<string, readonly [number, number]> = {\n` +
    `${linhas.join('\n')}\n` +
    `};\n\n` +
    `/** Dimensao real de uma foto local, ou undefined se ela nao esta no manifesto. */\n` +
    `export function getImageSize(src: string): readonly [number, number] | undefined {\n` +
    `  return IMAGE_SIZES[src.split('?')[0]];\n` +
    `}\n\n` +
    `export default IMAGE_SIZES;\n`;

  const out = path.resolve('src', 'lib', '_generated-image-sizes.ts');
  await fs.writeFile(out, conteudo, 'utf8');
  console.log(`[gen-image-sizes] ${chaves.length} imagens medidas → src/lib/_generated-image-sizes.ts`);
}

main().catch((err) => {
  console.error('[gen-image-sizes] falhou:', err.message || err);
  process.exit(0); // manifesto e otimizacao, nao pre-requisito do build
});
