#!/usr/bin/env node
import { promises as fs } from 'node:fs';
import path from 'node:path';

import sharp from 'sharp';

// Emite `src` + dimensoes reais de cada foto de public/clientes.
//
// Antes emitia so o caminho, e o album montava toda foto dentro de uma caixa
// 4/3 fixa com object-contain. As 37 fotos sao 15 retrato, 17 quadradas e 5
// paisagem: numa caixa deitada a foto mediana ocupava 75% do quadro e a mais
// estreita 40% -- o resto era fundo. Com largura e altura o album consegue
// montar mosaico em colunas, cada foto no proprio formato, sem corte e sem
// tarja. E `next/image` precisa das duas medidas para reservar o espaco antes
// de a imagem chegar, o que evita o layout pulando durante o carregamento.
const LARGURA_PADRAO = 1000;
const ALTURA_PADRAO = 1250;

async function main() {
  const publicDir = path.resolve('public', 'clientes');
  try {
    const entries = await fs.readdir(publicDir, { withFileTypes: true });
    const files = entries
      .filter((e) => e.isFile())
      .map((e) => e.name)
      .filter((n) => /\.(jpe?g|png|webp|avif)$/i.test(n))
      .sort((a, b) => a.localeCompare(b, 'pt-BR'));

    const list = [];
    for (const n of files) {
      let width = LARGURA_PADRAO;
      let height = ALTURA_PADRAO;
      try {
        const meta = await sharp(path.join(publicDir, n)).metadata();
        if (meta.width && meta.height) {
          width = meta.width;
          height = meta.height;
        } else {
          console.warn(`  aviso: ${n} sem dimensoes na metadata; usando ${width}x${height}`);
        }
      } catch (err) {
        // A foto entra assim mesmo: sumir com a prova social de um cliente por
        // causa de um header ilegivel e pior do que uma celula fora de medida.
        console.warn(`  aviso: nao consegui ler ${n} (${err.message}); usando ${width}x${height}`);
      }
      list.push({ src: `/clientes/${n}`, width, height });
    }

    const outPath = path.resolve('src', 'components', 'clientPhotos.ts');
    const header = `// AUTO-GENERATED by scripts/gen-client-photos.mjs\n`;
    const tipo = `export type ClientPhoto = { src: string; width: number; height: number };\n`;
    const body = `const CLIENT_PHOTOS: readonly ClientPhoto[] = ${JSON.stringify(list, null, 2)};\nexport default CLIENT_PHOTOS;\n`;
    await fs.writeFile(outPath, header + tipo + body, 'utf8');
    console.log(`Generated ${outPath} with ${list.length} items.`);
  } catch (err) {
    console.error('Failed to generate client photos:', err.message || err);
    process.exit(0); // do not fail build if folder missing
  }
}

main();
